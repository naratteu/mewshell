// Writes docs/gallery/README.md from the gallery apps, so the page always shows their real source.
// Run from the repository root: dotnet run eng/gallery.cs

using System.Text;

string[] order = ["gitview", "issues", "procs", "pinger", "brewview"];
const string Apps = "agent/skills/mewshell/gallery";

var page = new StringBuilder();
page.AppendLine("<!-- Generated by eng/gallery.cs from the files in agent/skills/mewshell/gallery. Do not edit. -->");
page.AppendLine();
page.AppendLine("# Gallery");
page.AppendLine();
page.AppendLine("Each app is one file. `dotnet run <file>.cs` runs it; `dotnet publish <file>.cs` makes one NativeAOT");
page.AppendLine("executable. The line count leaves out comments, blank lines and the `Platform` block at the end,");
page.AppendLine("which every app shares unchanged.");
page.AppendLine();
page.AppendLine(string.Join(" · ", order.Select(name => $"[{name}.cs](#{name}cs)")));

foreach (var name in order)
{
    var lines = File.ReadAllLines($"{Apps}/{name}.cs");
    var purpose = lines.First(l => l.StartsWith("// ")).TrimStart('/', ' ');
    var platform = Array.FindIndex(lines, l => l.StartsWith("static class Platform"));
    var count = lines.Take(platform < 0 ? lines.Length : platform).Count(l => l.Trim() is { Length: > 0 } t && !t.StartsWith("//"));

    page.AppendLine();
    page.AppendLine($"## {name}.cs");
    page.AppendLine();
    page.AppendLine($"{purpose.Split(" Run: ")[0]} **{count} lines.**");
    page.AppendLine();
    page.AppendLine($"![{name}]({name}.png)");
    page.AppendLine();
    page.AppendLine("```csharp");
    foreach (var line in lines) page.AppendLine(line);
    page.AppendLine("```");
}

File.WriteAllText("docs/gallery/README.md", page.ToString());
Console.WriteLine($"docs/gallery/README.md: {order.Length} apps");
